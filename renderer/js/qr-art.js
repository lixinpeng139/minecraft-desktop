const DARK = 'block/obsidian', LIGHT = 'block/quartz_block_side';

/** 每边的模块数（含静区与外圈） */
export const qrSpan = (code) => code.rows.length + (QUIET + RING) * 2;

/** 等待某个收款码需要的方块贴图加载完成（导出工具使用；界面里直接调用 renderQr，未加载时会自动重绘） */
export const loadQrTextures = (code) => Promise.all([DARK, LIGHT, code.ring].map(loadTex));

const cache = new Map();

/**
 * 把收款码画成一张离屏画布，每个模块 m×m 个设备像素。
 * 贴图尚未加载完时返回 null。
 */
export function renderQr(code, m) {
  const key = code.id + '|' + m;
  if (cache.has(key)) return cache.get(key);
  const dark = tex(DARK), light = tex(LIGHT), ring = tex(code.ring);
  if (!dark || !light || !ring) return null;
  const n = code.rows.length, span = qrSpan(code), off = QUIET + RING;
  const c = new OffscreenCanvas(span * m, span * m);
  const ctx = c.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  for (let y = 0; y < span; y++) {
    for (let x = 0; x < span; x++) {
      const qx = x - off, qy = y - off;
      let img = light;
      if (x < RING || y < RING || x >= span - RING || y >= span - RING) img = ring;
      else if (qx >= 0 && qy >= 0 && qx < n && qy < n && code.rows[qy][qx] === '#') img = dark;
      ctx.drawImage(img, x * m, y * m, m, m);
      // 黑曜石的高光太亮，扫码时会被当成浅色噪点：压暗到原来的 40%，只保留隐约的纹理
      if (img === dark) {
        ctx.fillStyle = 'rgba(0,0,0,0.6)';
        ctx.fillRect(x * m, y * m, m, m);
      }
    }
  }
  cache.set(key, c);
  return c;
}

/**
 * 在 Gfx 上绘制收款码：左上角 (x, y) 为 GUI 坐标，每个模块 m 个设备像素。
 * 绕过 GUI 缩放直接按设备像素绘制，保证模块边缘清晰、大小一致。
 */
export function drawQr(g, code, x, y, m) {
  const c = renderQr(code, m);
  if (!c) return;
  const ctx = g.ctx;
  ctx.save();
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  ctx.drawImage(c, Math.round(x * g.scale), Math.round(y * g.scale));
  ctx.restore();
  ctx.imageSmoothingEnabled = false;
}
